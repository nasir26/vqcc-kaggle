"""Copy the official metric notebook's code verbatim into harness/metric_vendor.py.

The harness imports read_circuit / read_npz / find_one / ALLOWED_INSTRUCTIONS etc. from that file
so that submission parsing and validation match the leaderboard exactly. Re-run after
`kaggle kernels pull metric/google-quantum-ai-metric -p data/metric -m` whenever the metric changes.

Usage: python tools/vendor_metric.py data/metric harness/metric_vendor.py
"""
import hashlib
import json
import pathlib
import sys


def main(metric_dir: str, out_path: str) -> None:
    metric = pathlib.Path(metric_dir)
    nb_path = metric / "google-quantum-ai-metric.ipynb"
    meta = json.loads((metric / "kernel-metadata.json").read_text(encoding="utf-8"))
    nb = json.loads(nb_path.read_text(encoding="utf-8"))
    code = "\n\n".join("".join(c["source"]) for c in nb["cells"] if c["cell_type"] == "code")
    digest = hashlib.sha256(nb_path.read_bytes()).hexdigest()
    header = (
        "# AUTO-GENERATED by tools/vendor_metric.py -- do not edit.\n"
        f"# Verbatim code of Kaggle notebook {meta['id']} (id_no {meta['id_no']}),\n"
        f"# docker image {meta['docker_image']},\n"
        f"# notebook sha256 {digest}.\n\n"
    )
    pathlib.Path(out_path).write_text(header + code + "\n", encoding="utf-8")
    print(f"wrote {out_path} from {nb_path} (sha256 {digest[:16]}...)")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
